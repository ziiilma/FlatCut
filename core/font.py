ALIAS = {'А': 'A', 'В': 'B', 'Е': 'E', 'Ё': 'E', 'К': 'K', 'М': 'M', 'Н': 'H', 'О': 'O', 'Р': 'P', 'С': 'C',
         'Т': 'T', 'Х': 'X', '×': 'X', 'Ъ': 'Ь'}
ADV = 5.0
CAP = 6.0


def glyph(ch):
    ch = ch.upper()
    ch = ALIAS.get(ch, ch)
    return GLYPHS.get(ch)


def supported(text):
    return sorted({c for c in text if c != ' ' and glyph(c) is None})


def strokes(text, h):
    k = h / CAP
    out = []
    x = 0.0
    for c in text:
        g = None if c == ' ' else glyph(c)
        if g:
            out += [[((x + px) * k, py * k) for px, py in line] for line in g]
        if c == ' ' or g:
            x += ADV
    w = max(0.0, (x - (ADV - 4)) * k)
    return out, w


def place(text, h, circles, polys, lines=(), gap=2.0, h_min=3.0):
    if not text.strip():
        return None, None
    outer, holes = G.rings_of(circles, polys)
    if not outer:
        return None, None
    xs, ys = [x for x, _ in outer], [y for _, y in outer]
    cx, cy = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
    hole_boxes = [(min(x for x, _ in r), min(y for _, y in r), max(x for x, _ in r), max(y for _, y in r)) for r in holes]
    while h >= h_min - 1e-9:
        txt, w = strokes(text, h)
        bw, bh = w + 2 * gap, h + 2 * gap
        sx, sy = max(xs) - min(xs) - bw, max(ys) - min(ys) - bh
        if sx >= 0 and sy >= 0:
            step = max(h / 3, (sx + sy) / 120, 0.5)
            cand = []
            for i in range(int(sx / step) + 1):
                for j in range(int(sy / step) + 1):
                    x0, y0 = min(xs) + i * step, min(ys) + j * step
                    cand.append((math.hypot(x0 + bw / 2 - cx, y0 + bh / 2 - cy), x0, y0))
            cand.sort()
            for _, x0, y0 in cand:
                if _fits(x0, y0, bw, bh, outer, holes, hole_boxes, lines):
                    ox, oy = x0 + gap, y0 + gap
                    return [[(x + ox, y + oy) for x, y in s] for s in txt], h
        h = h - 1.0 if h > 6 else h - 0.5
    return None, None


def _fits(x0, y0, bw, bh, outer, holes, hole_boxes, lines):
    x1, y1 = x0 + bw, y0 + bh
    pts = [(x0 + bw * a / 6, y0 + bh * b / 3) for a in range(7) for b in range(4)]
    if not all(G.inside(p, outer) for p in pts):
        return False
    if any(x0 < x < x1 and y0 < y < y1 for x, y in outer):
        return False
    for r, b in zip(holes, hole_boxes):
        if b[2] < x0 or b[0] > x1 or b[3] < y0 or b[1] > y1:
            continue
        if any(G.inside(p, r) for p in pts) or any(x0 < x < x1 and y0 < y < y1 for x, y in r):
            return False
    edges = [((x0, y0), (x1, y0)), ((x1, y0), (x1, y1)), ((x1, y1), (x0, y1)), ((x0, y1), (x0, y0))]
    for a, b in lines:
        if x0 < a[0] < x1 and y0 < a[1] < y1 or any(G.seg_x(a, b, c, d) for c, d in edges):
            return False
    return True
